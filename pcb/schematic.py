def R(ref, pos, value, a, b, rot=0, **f):
    txt = V_TXT if rot in (0, 180) else H_TXT
    return s.add(ref, "Device:R", pos, value, R0805, {"1": a, "2": b}, rot=rot,
                 fields=part(*PASSIVES[value], **f), **txt)


def C(ref, pos, value, a, b, fp=C0805, rot=0, **f):
    """Capacitor; a value like "2.2u 100V" shows the rating as its own line under the value."""
    txt = V_TXT if rot in (0, 180) else H_TXT
    cap, _, rating = value.partition(" ")
    fields = part(*PASSIVES[value], **f)
    show = None
    if rating:
        fields["Rating"] = rating
        show = ["Rating"]
    return s.add(ref, "Device:C", pos, cap, fp, {"1": a, "2": b}, rot=rot, fields=fields, show=show, **txt)


